//! V690_H1 52×52 artwork IDs from EDNewRes_Color.bin (color_res_lib.bin and color_res_dic.bin).
//! Names describe the artwork, not an action or key event. State names are based
//! on the extracted images; selecting disabled artwork does not disable a button.

macro_rules! images {
    ($($name:ident = $id:literal => $pressed:ident;)+) => {
        $(pub const $name: u32 = $id;)+

        /// (Name, image ID, image to show while pressed). Standalone state images
        /// retain their appearance while pressed. Order matches Inspector's picker.
        pub const ALL: &[(&str, u32, u32)] = &[
            $((stringify!($name), $name, $pressed),)+
        ];
    };
}

